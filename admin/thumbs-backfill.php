<?php
declare(strict_types=1);

define('IN_ADMIN', true);
require_once __DIR__ . '/../core/bootstrap.php';

use Core\Auth;
use Core\MediaLibrary;
use Core\MetaGallery;
use Core\Security;

header('Content-Type: application/json; charset=utf-8');

if (!Auth::check()) {
    http_response_code(401);
    echo json_encode(['ok' => false, 'error' => 'auth']);
    exit;
}

if (!Auth::can('manage_media') && !Auth::can('manage_pages') && !Auth::can('manage_settings')) {
    http_response_code(403);
    echo json_encode(['ok' => false, 'error' => 'forbidden']);
    exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    echo json_encode(['ok' => false, 'error' => 'method']);
    exit;
}

$token = isset($_POST['csrf']) && is_string($_POST['csrf']) ? $_POST['csrf'] : '';
if (!Security::verifyCsrfToken($token)) {
    http_response_code(403);
    echo json_encode(['ok' => false, 'error' => 'csrf']);
    exit;
}

// Thumbnail work is filesystem/CPU bound and can take a while; release the
// session lock so the admin can keep using the panel while it runs.
if (session_status() === PHP_SESSION_ACTIVE) {
    session_write_close();
}

@set_time_limit(0);
@ignore_user_abort(true);

$scope = isset($_POST['scope']) && is_string($_POST['scope']) ? (string) $_POST['scope'] : 'media';
if (!in_array($scope, ['gallery', 'media', 'selection', 'all'], true)) {
    $scope = 'media';
}
$force = isset($_POST['force']) && (string) $_POST['force'] === '1';
$offset = isset($_POST['offset']) ? max(0, (int) $_POST['offset']) : 0;
$limit = isset($_POST['limit']) ? max(1, min(20, (int) $_POST['limit'])) : 5;

if ($scope === 'gallery') {
    $widths = MediaLibrary::galleryThumbnailWidths();
    $items = array_map(
        static fn (string $path): array => ['path' => $path],
        MetaGallery::allGalleryImagePaths()
    );
} elseif ($scope === 'selection') {
    $rawPaths = $_POST['paths'] ?? '[]';
    $paths = is_string($rawPaths) ? json_decode($rawPaths, true) : $rawPaths;
    if (!is_array($paths)) {
        $paths = [];
    }
    $paths = array_values(array_filter(array_map(
        static fn ($path): string => trim((string) $path),
        $paths
    ), static fn (string $path): bool => $path !== ''));

    $widths = MediaLibrary::thumbnailGenerationWidths();
    $items = array_map(static fn (string $path): array => ['path' => $path], $paths);
} elseif ($scope === 'all') {
    $widths = MediaLibrary::thumbnailGenerationWidths();
    $items = MediaLibrary::listImages();
} else {
    // Media library backfill only warms admin preview sizes. Gallery widths
    // are generated by the targeted "gallery" scope and on upload/save.
    $widths = MediaLibrary::THUMBNAIL_PREVIEW_WIDTHS;
    $items = MediaLibrary::listImages();
}

$total = count($items);
$slice = array_slice($items, $offset, $limit);
$processed = 0;
$generated = 0;
$failed = 0;
$skipped = 0;
$errors = [];

foreach ($slice as $item) {
    $path = (string) ($item['path'] ?? '');
    if ($path === '') {
        $skipped++;
        continue;
    }

    $processed++;

    if ($widths === [] || !MediaLibrary::canGenerateThumbnail($path)) {
        $skipped++;
        continue;
    }

    if ($force) {
        // Delete only the sizes being rebuilt so other cached widths survive.
        MediaLibrary::deleteThumbnails($path, $widths);
        $needed = $widths;
    } else {
        $needed = [];
        foreach ($widths as $width) {
            if (!MediaLibrary::thumbnailExists($path, $width)) {
                $needed[] = $width;
            }
        }
    }
    if ($needed === []) {
        $skipped++;
        continue;
    }

    try {
        MediaLibrary::ensureThumbnails($path, $needed);
    } catch (\Throwable $e) {
        // A single broken file must not stop the whole batch.
    }

    if ($force) {
        try {
            // Also rebuild the WebP sibling with the corrected EXIF orientation.
            MediaLibrary::regenerateWebpSiblingForPath($path);
        } catch (\Throwable $e) {
            // WebP is optional; thumbnail generation still counts.
        }
    }

    $missing = [];
    foreach ($widths as $width) {
        if (!MediaLibrary::thumbnailExists($path, $width)) {
            $missing[] = $width;
        }
    }

    if ($missing === []) {
        $generated++;
    } else {
        $failed++;
        if (count($errors) < 25) {
            $errors[] = ['path' => $path, 'missing' => $missing];
        }
    }
}

$next = min($total, $offset + $limit);

echo json_encode([
    'ok'        => true,
    'scope'     => $scope,
    'widths'    => $widths,
    'total'     => $total,
    'offset'    => $offset,
    'next'      => $next,
    'processed' => $processed,
    'generated' => $generated,
    'failed'    => $failed,
    'skipped'   => $skipped,
    'errors'    => $errors,
    'done'      => $next >= $total,
], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
